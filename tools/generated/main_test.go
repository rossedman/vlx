package main

import (
	"bytes"
	"os"
	"path/filepath"
	"testing"
)

func TestRun(t *testing.T) {
	root := t.TempDir()
	write := func(name, body string) {
		p := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("go.mod", "module example.com/m\n")
	write("a.go", "package m\n")
	write("api/types.gen.go", "// Code generated by oapi-codegen. DO NOT EDIT.\n\npackage api\n")
	t.Chdir(root)

	tests := []struct {
		name     string
		gomod    string
		patterns []string
		code     int
		want     string
	}{
		{"lists generated files", "go.mod", []string{"./..."}, 0, "example.com/m/api/types.gen.go\n"},
		{"no go.mod", "missing.mod", []string{"./..."}, 2, ""},
		{"bad pattern", "go.mod", []string{"nope"}, 2, ""},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			var out, errOut bytes.Buffer
			if code := run(tt.gomod, tt.patterns, &out, &errOut); code != tt.code {
				t.Fatalf("run = %d, want %d (stderr %q)", code, tt.code, errOut.String())
			}
			if out.String() != tt.want {
				t.Errorf("output = %q, want %q", out.String(), tt.want)
			}
		})
	}
}
