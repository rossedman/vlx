package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

const documented = `// Package good is documented.
package good

// F does nothing.
func F() {}

// T is a type.
type T[K any] struct{}

// M does nothing.
func (*T[K]) M() {}
`

const undocumented = `package bad

func F() {}

type T struct{}

func (t *T) M() {}

type P[A, B any] struct{}

func (P[A, B]) N() {}
`

const generated = `// Code generated by x. DO NOT EDIT.

package gen

func F() {}
`

// dir writes body as a.go in a new temp dir and returns the dir.
func dir(t *testing.T, body string) string {
	t.Helper()
	d := t.TempDir()
	if err := os.WriteFile(filepath.Join(d, "a.go"), []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
	return d
}

func TestRun(t *testing.T) {
	tests := []struct {
		name     string
		body     string
		code     int
		wantOut  []string
		wantNone bool
	}{
		{name: "documented", body: documented, code: 0, wantNone: true},
		{name: "generated is skipped", body: generated, code: 0, wantNone: true},
		{name: "undocumented", body: undocumented, code: 1, wantOut: []string{
			"F has no doc comment",
			"T.M has no doc comment",
			"P.N has no doc comment",
			"package has no package comment",
		}},
		{name: "parse error", body: "package\n", code: 2, wantNone: true},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			var out, errOut bytes.Buffer
			if code := run([]string{dir(t, tt.body)}, &out, &errOut); code != tt.code {
				t.Fatalf("run = %d, want %d (stderr %q)", code, tt.code, errOut.String())
			}
			if tt.wantNone && out.Len() > 0 {
				t.Errorf("unexpected output %q", out.String())
			}
			for _, w := range tt.wantOut {
				if !strings.Contains(out.String(), w) {
					t.Errorf("output %q missing %q", out.String(), w)
				}
			}
			if got := strings.Count(out.String(), "\n"); len(tt.wantOut) > 0 && got != len(tt.wantOut) {
				t.Errorf("got %d findings, want %d:\n%s", got, len(tt.wantOut), out.String())
			}
		})
	}
}
