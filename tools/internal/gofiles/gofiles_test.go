package gofiles

import (
	"os"
	"path/filepath"
	"reflect"
	"testing"
)

// writeTree creates files (path → contents) under a new temp dir and
// returns it.
func writeTree(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for name, body := range files {
		p := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

func TestWalk(t *testing.T) {
	root := writeTree(t, map[string]string{
		"a.go":               "package a\n",
		"a_test.go":          "package a\n",
		"notes.txt":          "hi",
		"sub/b.go":           "// Code generated by x. DO NOT EDIT.\n\npackage sub\n",
		"sub/testdata/c.go":  "package c\n",
		".hidden/d.go":       "package d\n",
		"_skip/e.go":         "package e\n",
		"site/f.go":          "package f\n",
		"vendor/g/g.go":      "package g\n",
		"node_modules/h.go":  "package h\n",
		"other/deep/more.go": "package deep\n",
	})
	rel := func(p string) string { return filepath.ToSlash(filepath.Join(root, p)) }

	tests := []struct {
		name     string
		patterns []string
		want     []string
		gen      []bool
	}{
		{"recursive", []string{root + "/..."}, []string{rel("a.go"), rel("other/deep/more.go"), rel("sub/b.go")}, []bool{false, false, true}},
		{"single dir", []string{root}, []string{rel("a.go")}, []bool{false}},
		{"deduplicated", []string{root, root + "/..."}, []string{rel("a.go"), rel("other/deep/more.go"), rel("sub/b.go")}, []bool{false, false, true}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			files, err := Walk(tt.patterns)
			if err != nil {
				t.Fatal(err)
			}
			var got []string
			var gen []bool
			for _, f := range files {
				got = append(got, f.Path)
				gen = append(gen, f.Generated)
			}
			if !reflect.DeepEqual(got, tt.want) || !reflect.DeepEqual(gen, tt.gen) {
				t.Errorf("Walk = %v %v, want %v %v", got, gen, tt.want, tt.gen)
			}
		})
	}
}

func TestWalkDefaultPattern(t *testing.T) {
	root := writeTree(t, map[string]string{"x/a.go": "package x\n"})
	t.Chdir(root)
	files, err := Walk(nil)
	if err != nil {
		t.Fatal(err)
	}
	if len(files) != 1 || files[0].Path != "x/a.go" {
		t.Errorf("Walk(nil) = %+v, want x/a.go", files)
	}
}

func TestWalkErrors(t *testing.T) {
	root := writeTree(t, map[string]string{"bad/a.go": "package\n"})
	for _, p := range []string{
		filepath.Join(root, "missing"),
		filepath.Join(root, "missing") + "/...",
		filepath.Join(root, "bad"),
		root + "/...",
	} {
		if _, err := Walk([]string{p}); err == nil {
			t.Errorf("Walk(%q) succeeded, want error", p)
		}
	}
}

func TestModulePath(t *testing.T) {
	root := writeTree(t, map[string]string{
		"ok/go.mod":     "// comment\nmodule example.com/m\n\ngo 1.24\n",
		"quoted/go.mod": "module \"example.com/q\"\n",
		"none/go.mod":   "go 1.24\n",
	})
	tests := []struct {
		dir, want string
		wantErr   bool
	}{
		{"ok", "example.com/m", false},
		{"quoted", "example.com/q", false},
		{"none", "", true},
		{"missing", "", true},
	}
	for _, tt := range tests {
		got, err := ModulePath(filepath.Join(root, tt.dir, "go.mod"))
		if got != tt.want || (err != nil) != tt.wantErr {
			t.Errorf("ModulePath(%s) = %q, %v; want %q, err=%v", tt.dir, got, err, tt.want, tt.wantErr)
		}
	}
}
